import assert from 'node:assert/strict';
import { createNpcAutonomyPlanner } from './npc-autonomy.js';
import { createNpcPlanReassessment } from './npc-plan-reassessment.js';
const planner = createNpcAutonomyPlanner();
planner.registerPlan({ sessionId: 's1', branchId: 'b1', stateVersion: 'v1', npcId: 'captain', planId: 'escort', goal: '护送商队' });
const changes = [];
planner.subscribePlanChanges(change => changes.push(change));
const audit = [];
const reassessment = createNpcPlanReassessment({ autonomyPlanner: planner, onRequest: result => audit.push(result) });
const first = reassessment.request({ sessionId: 's1', branchId: 'b1', stateVersion: 'v1', npcId: 'captain', planId: 'escort', obstacle: { id: 'blocked-road', reason: '桥梁已损毁', factIds: ['bridge-out'] } });
assert.equal(first.status, 'needs_redecision');
const request = first;
assert.equal(reassessment.request({ sessionId: 's1', branchId: 'b1', stateVersion: 'v1', npcId: 'captain', planId: 'escort', obstacle: { id: 'blocked-road', reason: '桥梁已损毁', factIds: ['bridge-out'] } }).status, 'duplicate_reassessment');
assert.equal(audit.at(-1).status, 'duplicate_reassessment');
const adjusted = reassessment.adjust({ request, goal: '改走北路' });
assert.equal(adjusted.status, 'adjusted');
assert.equal(changes.at(-1).previousVersion, 1);
assert.equal(changes.at(-1).currentVersion, 2);
assert.deepEqual(adjusted.plan.lastEvidence.factIds, ['bridge-out']);
const pausedRequest = reassessment.request({ sessionId: 's1', branchId: 'b1', stateVersion: 'v1', npcId: 'captain', planId: 'escort', obstacle: { id: 'second-block', reason: '等待确认', factIds: ['bridge-out'] } });
assert.equal(reassessment.transition({ request: pausedRequest, status: 'paused', reason: '等待确认' }).status, 'transitioned');
assert.equal(planner.getPlan({ sessionId: 's1', branchId: 'b1', stateVersion: 'v1', npcId: 'captain', planId: 'escort' }).status, 'paused');
const terminalRequest = reassessment.request({ sessionId: 's1', branchId: 'b1', stateVersion: 'v1', npcId: 'captain', planId: 'escort', obstacle: { id: 'terminal-block', reason: '任务取消', factIds: ['bridge-out'] } });
const terminalTransition = reassessment.transition({ request: terminalRequest, status: 'cancelled', reason: '任务取消' });
assert.equal(terminalTransition.status, 'transitioned');
assert.equal(changes.at(-1).previousVersion, 3);
assert.equal(changes.at(-1).currentVersion, 4);
assert.equal(reassessment.clearForPlan({ sessionId: 's1', branchId: 'b1', stateVersion: 'v1', npcId: 'captain', planId: 'escort' }).status, 'already_cleared');
assert.equal(audit.at(-1).status, 'cleared');
planner.registerPlan({ sessionId: 's1', branchId: 'b1', stateVersion: 'v2', npcId: 'captain', planId: 'escort', goal: '新分支护送' });
const fresh = reassessment.request({ sessionId: 's1', branchId: 'b1', stateVersion: 'v2', npcId: 'captain', planId: 'escort', obstacle: { id: 'new-branch-block', reason: '新分支道路受阻', factIds: ['bridge-out'] } });
assert.equal(fresh.status, 'needs_redecision');
assert.equal(reassessment.clearForPlan({ sessionId: 's1', branchId: 'b1', stateVersion: 'v2', npcId: 'captain', planId: 'escort' }).status, 'cleared');
planner.registerPlan({ sessionId: 's1', branchId: 'b1', stateVersion: 'v1', npcId: 'captain', planId: 'escort', goal: '等待确认', version: 2 });
assert.equal(reassessment.adjust({ request, goal: '旧重评估' }).reason, 'plan_version_changed');
assert.equal(reassessment.request({ sessionId: 's1', branchId: 'b1', stateVersion: 'v1', npcId: 'captain', planId: 'escort', obstacle: { id: 'unsupported', reason: '听说道路有问题', factIds: [] } }).reason, 'obstacle_evidence_required');
assert.equal(audit.at(-1).status, 'needs_review');
assert.equal(reassessment.adjust({ request: { status: 'blocked' }, goal: '无依据' }).reason, 'reassessment_not_ready');
console.log('NPC plan reassessment tests passed');
