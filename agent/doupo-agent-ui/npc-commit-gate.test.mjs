import assert from 'node:assert/strict';
import { createNpcCommitGate } from './npc-commit-gate.js';
import { createNpcAutonomyPlanner } from './npc-autonomy.js';
import { createStateStore } from './state-store.js';
const planner = createNpcAutonomyPlanner();
const store = createStateStore();
store.seed({ sessionId: 's1', branchId: 'b1', stateVersion: 'v1', state: {} });
planner.registerPlan({ sessionId: 's1', branchId: 'b1', stateVersion: 'v1', npcId: 'n1', planId: 'p1', goal: '守住入口' });
const gate = createNpcCommitGate({ autonomyPlanner: planner, stateStore: store });
const candidate = { npcId: 'n1', planId: 'p1', planVersion: 1, sessionId: 's1', branchId: 'b1', stateVersion: 'v1', committed: false };
assert.equal(gate.check({ sessionId: 's1', branchId: 'b1', stateVersion: 'v1', candidates: [candidate] }).status, 'ready');
assert.equal(gate.check({ sessionId: 's1', branchId: 'b1', stateVersion: 'v1', candidates: [{ ...candidate, planVersion: 2 }] }).rejected[0].reason, 'plan_version_mismatch');
planner.adjustPlan({ sessionId: 's1', branchId: 'b1', stateVersion: 'v1', npcId: 'n1', planId: 'p1', baseVersion: 1, reason: '入口被封锁', goal: '转移到侧门', evidence: { factIds: ['gate-blocked'], summary: '入口已被封锁' } });
assert.equal(gate.check({ sessionId: 's1', branchId: 'b1', stateVersion: 'v1', candidates: [candidate] }).rejected[0].reason, 'plan_version_mismatch');
assert.equal(gate.check({ sessionId: 's1', branchId: 'b1', stateVersion: 'v0', candidates: [] }).reason, 'state_version_mismatch');
assert.equal(gate.check({ sessionId: 's1', branchId: 'b1', stateVersion: 'v1', candidates: [{ ...candidate, planVersion: 3 }] }).rejected[0].reason, 'plan_version_mismatch');
console.log('NPC commit gate tests passed');
