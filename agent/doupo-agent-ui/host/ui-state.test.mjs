import assert from 'node:assert/strict';
import { createUiState } from '../host/ui-state.js';

const ui = createUiState({ maxVisibleChanges: 1 });
const base = { sessionId: 's1', branchId: 'b1', stateVersion: 'v1' };
const ready = ui.updateProjection({ ...base, readState: 'ready', data: { location: '城门', health: 8 }, source: { version: 'v1' }, visibleFactIds: ['fact-1'], changes: [{ id: 'c1', text: '道路关闭' }, { id: 'secret', text: '不应显示' }] });
assert.equal(ready.readState, 'ready');
assert.equal(ready.truncated, true);
assert.equal(ready.changes.length, 1);
assert.equal(ui.getProjection(base).data.location, '城门');
const missing = createUiState().requestAction({ requestId: 'r0', ...base, action: 'view_task', targetId: 'task-1' });
assert.equal(missing.reason, 'projection_unavailable');
const invalid = ui.requestAction({ requestId: 'r1', ...base, action: 'delete_world', targetId: 'x' });
assert.equal(invalid.reason, 'unsupported_action');
const submitted = ui.requestAction({ requestId: 'r1', ...base, action: 'start_action', targetId: 'task-1', payload: { mode: 'inspect' } });
assert.equal(submitted.accepted, true);
assert.equal(submitted.request.executed, false);
assert.equal(ui.requestAction({ requestId: 'r1', ...base, action: 'start_action', targetId: 'task-1' }).reason, 'duplicate_request');
assert.equal(ui.requestAction({ requestId: 'r2', ...base, action: 'use_item', targetId: 'item-1' }).accepted, true);
assert.equal(ui.requestAction({ requestId: 'r3', ...base, action: 'view_task', targetId: 'task-1' }).accepted, true);
const stale = ui.requestAction({ requestId: 'r4', ...base, stateVersion: 'v2', action: 'continue_action', targetId: 'task-1' });
assert.equal(stale.reason, 'stale_projection');
assert.equal(ui.markAction('r1', 'completed').status, 'invalid_transition');
assert.equal(ui.markAction('r1', 'accepted', {}, { sessionId: 's1', branchId: 'b1' }).status, 'accepted');
assert.equal(ui.markAction('r1', 'completed', {}, { sessionId: 's1', branchId: 'b1' }).executed, true);
assert.equal(ui.markAction('r1', 'failed', {}, { sessionId: 's1', branchId: 'b1' }).status, 'terminal_request');
assert.equal(ui.markAction('missing', 'failed').status, 'unknown_request');
ui.updateProjection({ ...base, readState: 'failed', data: {}, changes: [] });
assert.equal(ui.getProjection(base).readState, 'failed');
ui.updateProjection({ sessionId: 's1', branchId: 'b2', stateVersion: 'v1', readState: 'ready', data: {} });
assert.equal(ui.requestAction({ requestId: 'r1', sessionId: 's1', branchId: 'b2', stateVersion: 'v1', action: 'view_task', targetId: 'task' }).accepted, true);
assert.equal(ui.markAction('r1', 'accepted').status, 'ambiguous_request');
assert.throws(() => ui.updateProjection({ ...base, readState: 'ready', visibleFactIds: [''], data: {} }), /visibleFactIds/);
assert.equal(ui.clearBranch('s1', 'b1'), 3);
assert.equal(ui.getProjection(base), undefined);
console.log('UI state tests passed');
