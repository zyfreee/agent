import assert from 'node:assert/strict';
import { createRequestRouter } from './request-router.js';
import { createRequestClassifier } from './request-classifier.js';
import { createModuleRunner } from './module-runner.js';
import { createOperationLedger } from './operation-ledger.js';

const runner = createModuleRunner({ updateTask() {} });
runner.register({ id: 'action-resolve', taskTypes: ['explicit_action'], stateChanging: true, run: ({ input }) => ({ npcCandidates: input.npcCandidates ?? [] }) });
const ledger = createOperationLedger();
const router = createRequestRouter({ classifier: createRequestClassifier(), runner, operationLedger: ledger, getEnabledModuleIds: () => ['action-resolve'], getCapabilities: () => ({ status: 'ready' }) });
const request = { requestId: 'npc-route', sessionId: 's1', branchId: 'b1', stateVersion: 'v1', input: '执行守门', playerConfirmed: true, interpretation: { type: 'explicit_action', task: 'explicit_action', explicitAction: true, playerAction: { method: 'use', targetId: 'gate' } } };
const run = await router.run({ request, taskId: 'npc-route', input: { intent: { method: 'use', targetId: 'gate' }, npcCandidates: [{  npcId: 'n1', planId: 'p1', planVersion: 1, sessionId: 's1', branchId: 'b1', stateVersion: 'v1' }] } });
assert.equal(run.status, 'executed');
const result = router.invalidateNpcPlanCandidates({ type: 'adjusted', previousVersion: 1, currentVersion: 2, plan: { npcId: 'n1', planId: 'p1', version: 2, sessionId: 's1', branchId: 'b1', stateVersion: 'v1' } });
assert.equal(result.status, 'invalidated');
assert.equal(result.planVersion, 1);
assert.equal(result.currentPlanVersion, 2);
assert.equal(result.invalidated[0].result.reason, 'npc_plan_changed');
assert.equal(result.invalidated[0].result.planVersion, 1);
assert.equal(result.invalidated[0].result.currentPlanVersion, 2);
assert.equal(router.invalidateNpcPlanCandidates({ previousVersion: 2, currentVersion: 3, plan: { npcId: 'n1', planId: 'p1', version: 3, sessionId: 's1', branchId: 'b1', stateVersion: 'v1', status: 'completed' } }).reason, 'npc_plan_terminal');
assert.equal(ledger.get('npc-route').status, 'history_invalidated');
assert.equal(router.revalidateCandidate({ requestId: 'npc-route' }).status, 'missing_candidate');
console.log('request router NPC invalidation tests passed');
