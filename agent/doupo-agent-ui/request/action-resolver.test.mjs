import assert from 'node:assert/strict';
import { createActionResolver } from '../request/action-resolver.js';

const resolver = createActionResolver({ now: () => 'test-time' });
const state = { player: { herbs: 1, health: 7 }, target: { open: true } };
const common = { sessionId: 'save-a', branchId: 'main', stateVersion: 'v1', actorId: 'player', targetId: 'target', method: 'use-herb', explicit: true };
const rules = [{ id: 'use-herb-v1', version: '1', targetId: 'target', method: 'use-herb', conditions: [{ targetId: 'player', field: 'herbs', op: 'gte', value: 1, reason: '没有草药' }], outcome: 'achieved', effects: [{ type: 'add', field: 'herbs', value: -1, reason: '消耗一份' }, { type: 'add', targetId: 'player', field: 'health', value: 2, reason: '恢复体力' }], elapsed: 0 }];
const result = resolver.resolve({ ...common, actionId: 'act-1', attemptId: 'try-1', intent: { ...common, explicit: true }, rules, state });
assert.equal(result.status, 'candidate');
assert.equal(result.outcome, 'achieved');
assert.equal(result.changes[0].after, 0);
assert.equal(result.changes[1].after, 9);
assert.equal(result.committed, false);
assert.equal(result.ruleVersion, '1');
assert.equal(result.authorizedAction, null);
assert.equal(state.player.herbs, 1, 'resolver must not mutate authoritative state');
const retry = resolver.resolve({ ...common, actionId: 'act-1', attemptId: 'try-1', intent: { ...common, explicit: true }, rules, state });
assert.equal(retry.replayed, true);
assert.deepEqual(retry.changes, result.changes);
const ambiguous = resolver.resolve({ ...common, actionId: 'act-2', attemptId: 'try-1', intent: { ...common, explicit: false }, rules, state });
assert.equal(ambiguous.status, 'needs_clarification');
assert.equal(ambiguous.reason, 'intent_not_explicit');
const noStock = resolver.resolve({ ...common, actionId: 'act-3', attemptId: 'try-1', intent: { ...common, explicit: true }, rules, state: { player: { herbs: 0 } } });
assert.equal(noStock.status, 'not_executable');
assert.equal(noStock.changes.length, 0);
const stale = resolver.resolve({ ...common, actionId: 'act-4', attemptId: 'try-1', stateVersion: 'v2', intent: { ...common, explicit: true }, rules, state });
assert.equal(stale.stateVersion, 'v2');
assert.equal(stale.status, 'candidate');
const impossible = resolver.resolve({ ...common, actionId: 'act-5', attemptId: 'try-1', intent: { ...common, explicit: true }, rules: [{ ...rules[0], effects: [{ type: 'add', field: 'herbs', value: -2 }] }], state });
assert.equal(impossible.status, 'blocked');
assert.equal(impossible.reason, 'resource_would_be_negative');
const noRule = resolver.resolve({ ...common, actionId: 'act-6', attemptId: 'try-1', intent: { ...common, explicit: true, method: 'unknown' }, rules, state });
assert.equal(noRule.reason, 'no_matching_rule');
const duplicateAttempt = resolver.resolve({ ...common, actionId: 'act-1', attemptId: 'try-1', branchId: 'other-branch', intent: { ...common, explicit: true }, rules, state });
assert.equal(duplicateAttempt.status, 'candidate', 'different branch keeps an independent idempotency key');
assert.equal(resolver.invalidate({ sessionId: 'save-a', branchId: 'main', actionId: 'act-1', attemptId: 'try-1' }), true);
assert.equal(resolver.invalidate({ sessionId: 'save-a', branchId: 'main', actionId: 'act-1', attemptId: 'try-1' }), false);
assert.equal(resolver.resolve({ ...common, actionId: 'bad', attemptId: 'bad', intent: { ...common, explicit: true }, rules: [{ ...rules[0], conditions: [{ targetId: 'player', field: 'has', op: 'mystery', value: 1 }] }], state }).reason, 'unsupported_condition');
assert.equal(resolver.resolve({ ...common, actionId: 'unauth', attemptId: '1', intent: { ...common, explicit: true, authorizedActions: ['target:inspect'] }, rules, state }).reason, 'player_action_not_authorized');
assert.throws(() => resolver.resolve({ ...common, actionId: 'nover', attemptId: '1', intent: { ...common, explicit: true }, rules: [{ ...rules[0], version: undefined }], state }), /version/);
assert.throws(() => resolver.resolve({ ...common, actionId: 'too-many', attemptId: '1', intent: { ...common, explicit: true }, rules: [{ ...rules[0], effects: Array(101).fill(rules[0].effects[0]) }], state }), /数量超出上限/);
console.log('action resolver tests passed');
