import assert from 'node:assert/strict';
import { createNarrativeGuard } from '../narrative/narrative-guard.js';

const guard = createNarrativeGuard({ maxClaims: 3 });
const base = { sessionId: 's1', branchId: 'b1', taskId: 'turn-1', stateVersion: 'v1', visibleFactIds: ['fact-road'], approvedChanges: [{ id: 'change-route' }] };
const candidate = guard.validate({ ...base, npcPlanVersions: [{ npcId: 'captain', planId: 'escort', version: 2 }], text: '你看到前方道路已经封闭。', claims: [{ id: 'c1', kind: 'fact', text: '道路封闭', factIds: ['fact-road'] }, { id: 'c2', kind: 'flavor', text: '风里带着尘土。', factIds: [] }] });
assert.equal(candidate.status, 'candidate');
assert.equal(candidate.committed, false);
assert.equal(candidate.playerActionAdded, false);
assert.deepEqual(candidate.npcPlanVersions, ['captain:escort:2']);
const invalidated = guard.invalidateNpcPlanVersion({ sessionId: 's1', branchId: 'b1', stateVersion: 'v1', npcId: 'captain', planId: 'escort', previousVersion: 2 });
assert.equal(invalidated.status, 'invalidated');
assert.equal(invalidated.cleared, 1);
assert.deepEqual(invalidated.taskIds, ['turn-1']);
assert.equal(guard.validate({ ...base, npcPlanVersions: [{ npcId: 'captain', planId: 'escort', version: 2 }], text: '旧计划正文', claims: [] }).status, 'candidate');
assert.equal(guard.validate({ ...base, text: '再次生成', claims: [] }).replayed, true);
const nextVersion = guard.validate({ ...base, stateVersion: 'v2', text: '新版本正文', claims: [{ id: 'v2', kind: 'fact', text: '新版本事实', factIds: ['fact-road'] }] });
assert.equal(nextVersion.status, 'candidate');
assert.equal(guard.validate({ ...base, stateVersion: 'v2', text: '重复新版本', claims: [] }).replayed, true);
assert.equal(guard.clearTask('s1', 'b1', 'v2', 'turn-1'), 1);
assert.equal(guard.validate({ ...base, stateVersion: 'v2', text: '清理单任务后正文', claims: [] }).status, 'candidate');
assert.equal(guard.clearStateVersion('s1', 'b1', 'v1') >= 1, true);
assert.equal(guard.validate({ ...base, stateVersion: 'v1', text: '清理后正文', claims: [] }).status, 'candidate');
const hidden = guard.validate({ ...base, taskId: 'turn-hidden', text: '敌人已经知道你的身份。', claims: [{ id: 'h', kind: 'fact', text: '敌人知情', factIds: ['secret-knowledge'] }] });
assert.equal(hidden.reason, 'unapproved_or_hidden_fact');
const malformed = guard.validate({ ...base, taskId: 'turn-malformed', text: '发生了变化。', claims: [{ id: 'm', kind: 'fact', text: '没有引用' }] });
assert.equal(malformed.reason, 'malformed_claims');
const playerAction = guard.validate({ ...base, taskId: 'turn-player', text: '你决定走上小路。', claims: [{ id: 'p', kind: 'fact', text: '玩家走上小路', factIds: ['change-route'], playerAction: true }] });
assert.equal(playerAction.playerActionAdded, true);
assert.throws(() => guard.validate({ ...base, taskId: 'turn-many', text: '文本', claims: [{ id: '1', kind: 'flavor', text: 'a' }, { id: '2', kind: 'flavor', text: 'b' }, { id: '3', kind: 'flavor', text: 'c' }, { id: '4', kind: 'flavor', text: 'd' }] }), /有界数组/);
const tooLong = createNarrativeGuard({ maxTextLength: 3 }).validate({ ...base, taskId: 'turn-long', text: '超过长度', claims: [] });
assert.equal(tooLong.reason, 'text_limit');
assert.equal(guard.validate({ ...base, taskId: 'turn-other', text: '使用已批准变化。', claims: [{ id: 'a', kind: 'fact', text: '路况改变', factIds: ['change-route'] }] }).status, 'candidate');
assert.equal(guard.clearBranch('s1', 'b1') >= 1, true);
console.log('narrative guard tests passed');
