import assert from 'node:assert/strict';
import { createOperationLedger } from '../core/operation-ledger.js';
const ledger = createOperationLedger({ maxRecords: 2, maxAttempts: 2 });
const operation = { operationId: 'op1', sessionId: 'chat1', branchId: 'branch1', triggerMessageId: 'msg1', taskId: 'task1', stateVersion: 'v1', timestamp: 10 };
assert.equal(ledger.start(operation).accepted, true);
assert.equal(ledger.start({ ...operation, taskId: 'task2' }).reason, 'duplicate_operation');
assert.equal(ledger.update('op1', 'completed_saved', { sessionId: 'chat1', branchId: 'branch1', stateVersion: 'v1', timestamp: 11 }).accepted, true);
assert.equal(ledger.start({ ...operation, taskId: 'task2' }).reason, 'duplicate_operation');
const retryable = { ...operation, operationId: 'op2', triggerMessageId: 'msg2' };
ledger.start(retryable);
assert.equal(ledger.update('op2', 'failed_unapplied', { timestamp: 12, reason: 'transient' }).accepted, true);
assert.equal(ledger.start({ ...retryable, taskId: 'task3', timestamp: 13 }).record.attempts, 2);
assert.equal(ledger.update('op2', 'failed_unapplied', { timestamp: 14, reason: 'retry failed' }).accepted, true);
assert.equal(ledger.start({ ...retryable, taskId: 'task4', timestamp: 15 }).reason, 'attempt_limit');
assert.equal(ledger.update('op2', 'processing', { stateVersion: 'old' }).reason, 'operation_terminal');
assert.equal(ledger.update('op1', 'history_invalidated', { sessionId: 'chat1', branchId: 'branch1', stateVersion: 'v1', reason: 'history_changed' }).accepted, true);
assert.equal(ledger.get('op1').status, 'history_invalidated');
const snapshot = ledger.get('op2'); snapshot.status = 'completed_saved';
assert.equal(ledger.get('op2').status, 'failed_unapplied');
const overflow = { ...operation, operationId: 'op3', triggerMessageId: 'msg3' };
ledger.start(overflow);
assert.equal(ledger.get('op1'), undefined);
assert.equal(ledger.list({ sessionId: 'chat1', limit: 1 }).length, 1);
assert.throws(() => ledger.start({ ...operation, operationId: 'bad', sessionId: '' }), /sessionId/);
assert.throws(() => ledger.list({ limit: 501 }), /limit/);
console.log('operation ledger tests passed');
