import assert from 'node:assert/strict';
import { createFactsLibrary } from './facts-library.js';

const library = createFactsLibrary();
library.registerSource({ id: 'novel-a', title: '示例正文', continuity: 'novel-main', edition: '底本A', realm: 'canon', provenance: '本地授权材料', coveredThrough: 12, missing: ['第7章'] });
library.registerSource({ id: 'comic-b', title: '漫画版', continuity: 'comic', edition: '漫画版B', realm: 'adaptation', provenance: '单独登记的改编版本' });
library.registerFact({ id: 'f-early', sourceId: 'novel-a', subject: '林岚', aliases: ['小岚'], predicate: '知道', text: '早期不知道北门暗号', phase: 2, evidenceKind: 'stated', location: '第2章', evidence: '原文单元 u2', polarity: 'negative' });
library.registerFact({ id: 'f-late', sourceId: 'novel-a', subject: '林岚', predicate: '知道', text: '后来得知北门暗号', phase: 8, evidenceKind: 'character-claim', location: '第8章', polarity: 'positive' });
library.registerFact({ id: 'f-comic', sourceId: 'comic-b', subject: '林岚', predicate: '知道', text: '漫画中很早就知道暗号', phase: 1, evidenceKind: 'inference' });

assert.equal(library.query({ query: '暗号' }).status, 'needs_scope');
assert.equal(library.query({ query: '暗号', sourceIds: ['novel-a'], asOf: 3 }).results.length, 1);
assert.equal(library.query({ query: '暗号', sourceIds: ['novel-a'], asOf: 3 }).status, 'supported');
const full = library.query({ query: '暗号', sourceIds: ['novel-a'], asOf: 9 });
assert.equal(full.status, 'conflict');
assert.deepEqual(full.conflicts[0].factIds, ['f-early', 'f-late']);
assert.equal(full.results[1].evidenceKind, 'character-claim');
assert.equal(library.query({ query: '暗号', sourceIds: ['comic-b'] }).results[0].continuity, 'comic');
assert.equal(library.query({ query: '不存在', sourceIds: ['novel-a'] }).status, 'not_found');
const actorKnown = library.queryForActor({ actorId: 'npc-1', knownFactIds: ['f-early'], query: '暗号', sourceIds: ['novel-a'], asOf: 9 });
assert.equal(actorKnown.status, 'supported');
assert.deepEqual(actorKnown.results.map(f => f.id), ['f-early']);
assert.equal(actorKnown.conflicts.length, 0);
assert.equal(actorKnown.hiddenCount, 1);
const actorUnaware = library.queryForActor({ actorId: 'npc-2', knownFactIds: [], query: '暗号', sourceIds: ['novel-a'], asOf: 9 });
assert.equal(actorUnaware.status, 'not_known_to_actor');
assert.equal(actorUnaware.results.length, 0);
assert.throws(() => library.queryForActor({ actorId: 'npc-3', knownFactIds: 'f-early', query: '暗号', sourceIds: ['novel-a'] }), /有界文本数组/);
assert.match(library.query({ query: '不存在', sourceIds: ['novel-a'] }).note, /不表示原著中不存在/);
assert.throws(() => library.registerFact({ id: 'dangling', sourceId: 'absent', subject: '人', predicate: '知', text: '内容' }), /未登记来源/);
assert.throws(() => library.registerSource({ id: 'novel-a', title: '重复', continuity: 'x', edition: 'x', provenance: 'x' }), /已登记/);
const capped = library.query({ query: '暗号', sourceIds: ['novel-a'], limit: 1 });
assert.equal(capped.status, 'partial');
assert.equal(capped.results.length, 1);
const missingStage = createFactsLibrary();
missingStage.registerSource({ id: 'unknown-phase', title: '未核期材料', continuity: 'novel-main', edition: '不明', provenance: '待核' });
missingStage.registerFact({ id: 'unknown', sourceId: 'unknown-phase', subject: '人', predicate: '能力', text: '有某能力' });
assert.equal(missingStage.query({ query: '能力', sourceIds: ['unknown-phase'], asOf: 3 }).status, 'not_found');

const beforeUpdate = library.query({ query: '暗号', sourceIds: ['novel-a'] });
assert.equal(beforeUpdate.sources[0].revision, 1);
assert.deepEqual(library.updateSource('novel-a', { coveredThrough: 14 }, { expectedRevision: 0, reason: 'stale update' }), { accepted: false, reason: 'revision_mismatch', currentRevision: 1 });
const updated = library.updateSource('novel-a', { coveredThrough: 14, missing: ['第7章', '第13章'] }, { expectedRevision: 1, reason: 'added coverage evidence' });
assert.equal(updated.revision, 2);
assert.deepEqual(updated.affectedFactIds, ['f-early', 'f-late']);
assert.equal(library.query({ query: '暗号', sourceIds: ['novel-a'] }).status, 'not_found');
assert.deepEqual(library.listFactsNeedingReview().map(f => f.id), ['f-early', 'f-late']);
assert.equal(library.listSourceRevisions('novel-a').length, 2);
assert.equal(library.listSourceRevisions('novel-a')[0].source.coveredThrough, 12);
assert.equal(library.listSourceRevisions('novel-a')[1].source.coveredThrough, 14);
assert.equal(library.reviewFact('f-early', { expectedSourceRevision: 1, decision: 'confirmed' }).reason, 'revision_mismatch');
assert.equal(library.reviewFact('f-early', { expectedSourceRevision: 2, decision: 'confirmed', note: '回查新增来源版本' }).accepted, true);
assert.equal(library.query({ query: '暗号', sourceIds: ['novel-a'] }).results.some(f => f.id === 'f-early'), true);
assert.equal(library.listFactsNeedingReview().length, 1);
console.log('facts library tests passed');
