import assert from 'node:assert/strict';
import { createNpcDecisionGuard } from '../npc/npc-decision-guard.js';

const guard = createNpcDecisionGuard();
const base = { sessionId: 's1', branchId: 'b1', taskId: 'turn-1', stateVersion: 'v1', npcId: 'captain', permission: { npcId: 'captain', allowed: true }, envelope: { npcId: 'captain', knownFactIds: ['bridge-out', 'player-warning'] } };
const hiddenSecret = guard.review({ ...base, proposal: { intent: 'refuse', evidenceFactIds: ['secret-location'] } });
assert.equal(hiddenSecret.status, 'rejected');
assert.equal(hiddenSecret.reason, 'out_of_knowledge_scope');
assert.deepEqual(hiddenSecret.rejectedFactIds, ['secret-location']);
const noAuthority = guard.review({ ...base, permission: { npcId: 'captain', allowed: false }, proposal: { intent: 'accept' } });
assert.equal(noAuthority.status, 'blocked');
assert.equal(noAuthority.reason, 'missing_decision_authority');
const ask = guard.review({ ...base, proposal: { intent: 'ask', evidenceFactIds: ['player-warning'], requiresPlayerResponse: true, rationale: '需先核实断桥' } });
assert.equal(ask.status, 'waiting_player');
assert.equal(ask.pauseBeforeAction, true);
assert.equal(ask.formalFact, false);
assert.equal(ask.committed, false);
assert.equal(guard.review({ ...base, proposal: { intent: 'accept' } }).replayed, true);
const action = guard.review({ ...base, taskId: 'turn-action', proposal: { intent: 'action_intent', evidenceFactIds: ['bridge-out'], action: { targetId: 'bridge', method: 'inspect' }, requiresPlayerResponse: false } });
assert.equal(action.status, 'action_proposed');
assert.equal(action.executed, false);
assert.deepEqual(action.actionIntent, { targetId: 'bridge', method: 'inspect' });
const denied = guard.review({ ...base, taskId: 'turn-denied', permission: undefined, proposal: { intent: 'refuse' } });
assert.equal(denied.reason, 'missing_decision_authority');
const invalid = guard.review({ ...base, taskId: 'turn-invalid', proposal: { intent: 'decide-everything' } });
assert.equal(invalid.reason, 'unsupported_intent');
const plan = guard.review({ ...base, taskId: 'turn-plan', proposal: { intent: 'wait', evidenceFactIds: ['bridge-out'], plan: { id: 'check-road', goal: '调查道路', status: 'proposed' } } });
assert.equal(plan.plan.formal, false);
assert.equal(guard.getPlan({ sessionId: 's1', branchId: 'b1', npcId: 'captain', planId: 'check-road' }).goal, '调查道路');
const conflict = guard.review({ ...base, taskId: 'turn-plan2', proposal: { intent: 'wait', plan: { id: 'check-road', goal: '直接绕行', baseVersion: 0 } } });
assert.equal(conflict.reason, 'plan_version_conflict');
const intentDenied = guard.review({ ...base, taskId: 'turn-intent-denied', permission: { ...base.permission, allowedIntents: ['wait'] }, proposal: { intent: 'refuse' } });
assert.equal(intentDenied.reason, 'intent_not_permitted');
const actionDenied = guard.review({ ...base, taskId: 'turn-action-denied', permission: { ...base.permission, allowedActions: ['gate:inspect'] }, proposal: { intent: 'action_intent', action: { targetId: 'bridge', method: 'burn' } } });
assert.equal(actionDenied.reason, 'action_not_permitted');
const actionAllowed = guard.review({ ...base, taskId: 'turn-action-allowed', permission: { ...base.permission, allowedActions: ['bridge:inspect'] }, proposal: { intent: 'action_intent', action: { targetId: 'bridge', method: 'inspect' } } });
assert.equal(actionAllowed.authorizedAction, 'bridge:inspect');
const stalePermission = guard.review({ ...base, taskId: 'turn-stale-permission', permission: { ...base.permission, stateVersion: 'v0' }, proposal: { intent: 'wait' } });
assert.equal(stalePermission.status, 'stale_state');
assert.throws(() => guard.review({ ...base, taskId: 'turn-bad-knowledge', envelope: { npcId: 'captain', knownFactIds: [''] }, proposal: { intent: 'wait' } }), /knownFactIds/);
assert.equal(guard.clearBranch('s1', 'b1') >= 1, true);
assert.equal(guard.getPlan({ sessionId: 's1', branchId: 'b1', npcId: 'captain', planId: 'check-road' }), undefined);
console.log('NPC decision guard tests passed');
